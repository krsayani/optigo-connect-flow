const stamp = { createdAt: SEED_TS, updatedAt: SEED_TS };

function vision(
  id: string,
  code: string,
  name: string,
  description: string,
  sortOrder: number,
): VisionType {
  return { id, code, name, description, active: true, sortOrder };
}

function design(
  id: string,
  visionTypeId: string,
  code: string,
  name: string,
  flags: {
    add?: boolean;
    seg?: boolean;
    fit?: boolean;
    pow?: boolean;
    minFit?: number | null;
  },
  sortOrder: number,
): LensDesign {
  return {
    id,
    visionTypeId,
    code,
    name,
    description: name,
    requiresAddPower: flags.add === true,
    requiresSegmentHeight: flags.seg === true,
    requiresFittingHeight: flags.fit === true,
    requiresPositionOfWear: flags.pow === true,
    minimumFittingHeight: flags.minFit ?? null,
    active: true,
    sortOrder,
  };
}

function material(
  id: string,
  code: string,
  name: string,
  refractiveIndex: number,
  impactResistant: boolean,
  sortOrder: number,
  abbeValue: number | null = null,
): LensMaterial {
  return {
    id,
    code,
    name,
    refractiveIndex,
    abbeValue,
    specificGravity: null,
    impactResistant,
    active: true,
    sortOrder,
  };
}

