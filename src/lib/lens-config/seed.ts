function coat(
  id: string,
  name: string,
  code: string,
  coatingTier: Coating["coatingTier"],
  arLevel: Coating["arLevel"],
  hardCoat: boolean,
  front: boolean,
  back: boolean,
  blue: Coating["blueLightFilterType"] = "NONE",
): Coating {
  return {
    id,
    organizationId: null,
    manufacturerId: null,
    name,
    code,
    coatingTier,
    hardCoat,
    arLevel,
    frontSurfaceAr: front,
    backSurfaceAr: back,
    blueLightFilterType: blue,
    uvProtection: true,
    hydrophobic: arLevel !== "NONE",
    oleophobic: arLevel === "PREMIUM" || arLevel === "ULTRA_PREMIUM",
    antiStatic: arLevel === "ULTRA_PREMIUM",
    antiSmudge: arLevel !== "NONE",
    dustResistant: arLevel === "ULTRA_PREMIUM",
    antiFog: false,
    reflectionColor: null,
    warrantyMonths: arLevel === "ULTRA_PREMIUM" ? 24 : arLevel === "PREMIUM" ? 12 : null,
    description: name,
    active: true,
    createdBy: null,
    ...stamp,
  };
}

